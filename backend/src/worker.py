"""OAuth broker for the gdrive-reader Claude Code plugin (FastAPI on Cloudflare Python Workers).

Why it exists: Google's "Web application" OAuth client requires a client secret
for the code exchange and for token refresh. Keeping that secret here, instead
of shipping it inside the plugin, means anyone who installs the plugin can sign
in without ever seeing it.

What it does, and nothing more:
  GET  /oauth/start     build Google's consent URL (adds client_id, scope, redirect_uri)
  GET  /oauth/callback  receive Google's redirect and relay code+state to the user's
                        local listener at http://127.0.0.1:<port>/callback
  POST /oauth/token     exchange code + PKCE verifier for tokens (adds client_secret)
  POST /oauth/refresh   refresh an access token (adds client_secret)

It is stateless: no database, no token storage, no logging of request bodies.
Drive file contents never pass through it; the plugin calls Google Drive directly.

Configuration (Worker secrets): GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET.
Optional: PUBLIC_BASE_URL (defaults to the URL the request arrived on).
"""

from __future__ import annotations

import os
import re
from typing import Any
from urllib.parse import urlencode

import httpx
from fastapi import FastAPI, Request
from fastapi.responses import HTMLResponse, JSONResponse, RedirectResponse
from pydantic import BaseModel, Field

GOOGLE_AUTH_URL = "https://accounts.google.com/o/oauth2/v2/auth"
GOOGLE_TOKEN_URL = "https://oauth2.googleapis.com/token"  # noqa: S105 - endpoint URL, not a secret
DRIVE_READONLY_SCOPE = "https://www.googleapis.com/auth/drive.readonly"

# state = "<loopback port>.<random nonce>", generated by the plugin.
STATE_RE = re.compile(r"^(?P<port>\d{4,5})\.(?P<nonce>[A-Za-z0-9_-]{16,128})$")
CHALLENGE_RE = re.compile(r"^[A-Za-z0-9_-]{43,128}$")
NO_STORE = {"Cache-Control": "no-store", "Pragma": "no-cache", "Referrer-Policy": "no-referrer"}
_TOKEN_FIELDS = ("access_token", "expires_in", "refresh_token", "scope", "token_type")


class TokenRequest(BaseModel):
    code: str = Field(min_length=1, max_length=2048)
    code_verifier: str = Field(pattern=r"^[A-Za-z0-9._~-]{43,128}$")


class RefreshRequest(BaseModel):
    refresh_token: str = Field(min_length=1, max_length=2048)


def _setting(request: Request, name: str) -> str | None:
    env = request.scope.get("env")  # Cloudflare bindings, provided by workers.asgi
    value = getattr(env, name, None) if env is not None else None
    if value is None:
        value = os.environ.get(name)  # local runs (tests, uvicorn)
    return str(value) if value else None


def _base_url(request: Request) -> str:
    configured = _setting(request, "PUBLIC_BASE_URL")
    if configured:
        return configured.rstrip("/")
    return f"{request.url.scheme}://{request.url.netloc}"


def _parse_state(state: str | None) -> int | None:
    match = STATE_RE.match(state or "")
    if not match:
        return None
    port = int(match.group("port"))
    return port if 1024 <= port <= 65535 else None


def _error(status: int, error: str, description: str) -> JSONResponse:
    return JSONResponse({"error": error, "error_description": description}, status_code=status, headers=NO_STORE)


def _page(status: int, title: str, body: str) -> HTMLResponse:
    html = (
        '<!doctype html><html lang="zh-Hant"><head><meta charset="utf-8"><title>Google Drive Reader</title></head>'
        '<body style="font-family:system-ui,sans-serif;max-width:36rem;margin:4rem auto;line-height:1.6">'
        f"<h1>{title}</h1><p>{body}</p></body></html>"
    )
    return HTMLResponse(html, status_code=status, headers=NO_STORE)


def create_app(transport: httpx.AsyncBaseTransport | None = None) -> FastAPI:
    app = FastAPI(title="gdrive-reader OAuth broker", docs_url=None, redoc_url=None, openapi_url=None)

    async def call_google(form: dict[str, str]) -> JSONResponse:
        try:
            async with httpx.AsyncClient(transport=transport, timeout=15.0) as client:
                resp = await client.post(GOOGLE_TOKEN_URL, data=form)
        except httpx.HTTPError:
            return _error(502, "upstream_unreachable", "Could not reach Google's token endpoint.")
        try:
            body: dict[str, Any] = resp.json()
        except ValueError:
            body = {}
        if resp.status_code == 200 and body.get("access_token"):
            return JSONResponse({k: body[k] for k in _TOKEN_FIELDS if k in body}, headers=NO_STORE)
        if resp.status_code in (400, 401):
            # Pass Google's error code through (e.g. invalid_grant) so the plugin can react.
            return _error(400, str(body.get("error", "invalid_request")), str(body.get("error_description", "")))
        return _error(502, "upstream_error", f"Google returned HTTP {resp.status_code}.")

    def credentials(request: Request) -> tuple[str, str] | None:
        client_id = _setting(request, "GOOGLE_CLIENT_ID")
        client_secret = _setting(request, "GOOGLE_CLIENT_SECRET")
        return (client_id, client_secret) if client_id and client_secret else None

    @app.get("/")
    async def index() -> dict[str, Any]:
        return {
            "service": "gdrive-reader OAuth broker",
            "endpoints": ["/oauth/start", "/oauth/callback", "/oauth/token", "/oauth/refresh", "/healthz"],
            "stores_tokens": False,
        }

    @app.get("/healthz")
    async def healthz(request: Request) -> dict[str, bool]:
        return {"ok": True, "configured": credentials(request) is not None}

    @app.get("/oauth/start")
    async def start(request: Request, code_challenge: str = "", state: str = ""):
        creds = credentials(request)
        if creds is None:
            return _page(500, "後端尚未設定", "OAuth 後端缺少 GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET。")
        if not CHALLENGE_RE.match(code_challenge) or _parse_state(state) is None:
            return _page(400, "授權參數錯誤", "缺少或格式錯誤的 code_challenge / state。請回到 Claude Code 重新授權。")
        query = urlencode(
            {
                "client_id": creds[0],
                "redirect_uri": f"{_base_url(request)}/oauth/callback",
                "response_type": "code",
                "scope": DRIVE_READONLY_SCOPE,
                "access_type": "offline",  # we need a refresh token
                "prompt": "select_account consent",  # always pick the account; always return a refresh token
                "code_challenge": code_challenge,
                "code_challenge_method": "S256",
                "state": state,
            }
        )
        return RedirectResponse(f"{GOOGLE_AUTH_URL}?{query}", status_code=302, headers=NO_STORE)

    @app.get("/oauth/callback")
    async def callback(request: Request):
        params = request.query_params
        port = _parse_state(params.get("state"))
        if port is None:
            return _page(400, "授權驗證失敗", "state 參數缺少或格式錯誤。請回到 Claude Code 重新授權。")
        relay = {key: params[key] for key in ("code", "state", "error") if key in params}
        target = f"http://127.0.0.1:{port}/callback?{urlencode(relay)}"
        return RedirectResponse(target, status_code=302, headers=NO_STORE)

    @app.post("/oauth/token")
    async def token(request: Request, body: TokenRequest):
        creds = credentials(request)
        if creds is None:
            return _error(500, "server_misconfigured", "GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET are not set.")
        return await call_google(
            {
                "grant_type": "authorization_code",
                "code": body.code,
                "code_verifier": body.code_verifier,
                "client_id": creds[0],
                "client_secret": creds[1],
                "redirect_uri": f"{_base_url(request)}/oauth/callback",
            }
        )

    @app.post("/oauth/refresh")
    async def refresh(request: Request, body: RefreshRequest):
        creds = credentials(request)
        if creds is None:
            return _error(500, "server_misconfigured", "GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET are not set.")
        return await call_google(
            {
                "grant_type": "refresh_token",
                "refresh_token": body.refresh_token,
                "client_id": creds[0],
                "client_secret": creds[1],
            }
        )

    return app


app = create_app()

try:  # Only available inside the Cloudflare Workers runtime.
    from workers import asgi
except ImportError:  # pragma: no cover - tests and local uvicorn runs
    asgi = None

if asgi is not None:  # pragma: no cover
    Default = asgi.entrypoint(app)
